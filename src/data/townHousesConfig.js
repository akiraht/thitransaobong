/**
 * TỰ ĐỘNG TÍNH TOÁN CÁC HỘP VA CHẠM VẬT LÝ (TOWN_OBSTACLES)
 * Ôm khít 100% phần chân và thân của từng ngôi nhà.
 * Khi dời vị trí nhà (x, y), hộp va chạm TỰ ĐỘNG mapping theo ngay lập tức!
 */
export function getTownObstacles() {
  return TOWN_HOUSES_DATA.map((h) => {
    const halfW = (h.collisionW || 6.5) * 0.45;
    const height = h.collisionH || 8.0;
    return {
      id: `${h.id}_obstacle`,
      name: h.signName || h.name,
      xMin: Number((h.x - halfW).toFixed(2)),
      xMax: Number((h.x + halfW).toFixed(2)),
      yMin: Number((h.y - height * 0.75).toFixed(2)),
      yMax: Number((h.y + 0.5).toFixed(2)),
      color: '#EF4444',
      bg: 'rgba(239, 68, 68, 0.35)'
    };
  });
}

/**
 * TỰ ĐỘNG TÍNH TOÁN CÁC VÙNG KÍCH HOẠT HỘI THOẠI (HILL_LANDMARKS)
 * Đặt ngay tại bậc thềm trước cửa từng ngôi nhà.
 * Khi dời vị trí nhà (x, y), vùng kích hoạt TỰ ĐỘNG mapping theo ngay lập tức!
 */
export function getHillLandmarks() {
  return TOWN_HOUSES_DATA.map((h) => ({
    id: h.id,
    type: h.type || 'character',
    charId: h.charId || h.id,
    name: h.name,
    signName: h.signName || h.name,
    houseTitle: h.houseTitle || h.signName || h.name,
    x: h.x,
    y: Number((h.y + 1.2).toFixed(2)),
    radius: h.triggerRadius || 7.0,
    speaker: h.speaker || h.name,
    dialogue: h.dialogue,
    actionText: h.actionText,
    icon: h.icon,
    badgeBg: h.badgeBg || '#FFF4BD'
  }));
}
